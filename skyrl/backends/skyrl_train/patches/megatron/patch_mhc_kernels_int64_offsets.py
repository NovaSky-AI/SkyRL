"""megatron-core's fused mHC Triton kernels: 64-bit row offsets for long sequences.

``fused_mhc_kernels`` (hyper-connection aggregate and H_post BDA, forward and backward) index rows with
``offs_s = tl.program_id(0) * BLOCK_S + ...`` in int32 and multiply by the row stride ``n * C`` (the ``n``
hyper-connection streams of ``C`` channels). Past ``2**31 / (n * C)`` rows that wraps: DeepSeek-V4 / V4.1
(``n = 4``, ``C = 5120``) at more than ~104k tokens per micro-batch reads out of bounds
(``Triton Error [CUDA]: an illegal memory access`` in ``_triton_h_agg_fwd_kernel``, e.g. at 256k context).
Any mHC model hits it once ``tokens * n * hidden`` reaches 2**31.

The upstream fix is one line per kernel, ``pid_s = tl.program_id(0).to(tl.int64)`` (the shape
NVIDIA/Megatron-LM#8487 uses for the CSA THD indexer kernels). Rather than vendoring the kernels, this
reads the four kernel definitions from the installed ``fused_mhc_kernels`` source, applies exactly that
change, builds them in a generated module that shares the original module's globals, and rebinds them on
the original module (its launchers look the kernels up there at call time). If the pinned source no longer
has the int32 line (fixed upstream) or a kernel is missing, the patch is skipped.

Remove when the pinned megatron-core computes these offsets in int64.
"""

import ast
import hashlib
import importlib.util
import os
import tempfile

from loguru import logger

_APPLIED = False
KERNELS = (
    "_triton_h_agg_fwd_kernel",
    "_triton_hpb_fwd_kernel",
    "_triton_hpb_bwd_g_x_orig_kernel",
    "_triton_hpb_bwd_g_hp_hr_kernel",
)
INT32_ROW = "pid_s = tl.program_id(0)\n"
INT64_ROW = "pid_s = tl.program_id(0).to(tl.int64)\n"


def _kernel_sources(source: str) -> dict:
    """Decorated source of each kernel in ``KERNELS``, dedented, with the int64 row index."""
    lines = source.splitlines(keepends=True)
    out = {}
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.FunctionDef) and node.name in KERNELS:
            start = min([d.lineno for d in node.decorator_list] + [node.lineno]) - 1
            block = lines[start : node.end_lineno]
            indent = len(block[0]) - len(block[0].lstrip())
            text = "".join(line[indent:] if line.strip() else line for line in block)
            if text.count(INT32_ROW.strip()) != 1:
                return {}
            out[node.name] = text.replace(INT32_ROW, INT64_ROW)
    return out if len(out) == len(KERNELS) else {}


def apply_mhc_kernels_int64_offsets_patch() -> bool:
    """Rebind the four row-indexed mHC kernels to int64-offset copies. Idempotent; ``False`` if skipped."""
    global _APPLIED
    if _APPLIED:
        return True
    try:
        from megatron.core.fusions import fused_mhc_kernels as mhc
    except ImportError:
        return False
    if not all(hasattr(mhc, name) for name in KERNELS):
        return False
    with open(mhc.__file__) as f:
        kernels = _kernel_sources(f.read())
    if not kernels:
        logger.info("mHC kernels: int32 row offsets not found in the pinned source; int64 patch not applied")
        return False

    body = "\n\n".join(kernels[name] for name in KERNELS)
    text = (
        '"""Generated by SkyRL patch_mhc_kernels_int64_offsets.py from megatron-core fused_mhc_kernels."""\n'
        "import megatron.core.fusions.fused_mhc_kernels as _source\n\n"
        "globals().update({k: v for k, v in vars(_source).items() if not k.startswith('__')})\n\n\n" + body
    )
    digest = hashlib.sha256(text.encode()).hexdigest()[:16]
    # Triton reads a kernel's source from its file, so the module lives on disk (one per source version).
    directory = os.path.join(tempfile.gettempdir(), "skyrl_generated_kernels")
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, f"mhc_kernels_int64_{digest}.py")
    if not os.path.exists(path):
        tmp = f"{path}.{os.getpid()}.tmp"
        with open(tmp, "w") as f:
            f.write(text)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(f"skyrl_mhc_kernels_int64_{digest}", path)
    generated = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generated)
    for name in KERNELS:
        setattr(mhc, name, getattr(generated, name))
    _APPLIED = True
    logger.info("mHC kernels: int64 row offsets (sequences past 2**31 / (n_streams * hidden) rows)")
    return True
